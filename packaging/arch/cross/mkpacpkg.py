#!/usr/bin/env python3
"""Build a pacman package (.pkg.tar.zst) from a staged directory, without makepkg.

usage: mkpacpkg.py STAGE META.json OUTDIR [INSTALL_SCRIPT]

META.json keys: pkgname pkgver(full, e.g. 1:26.2.6-1) pkgdesc url arch license(list)
 depend provides conflicts replaces optdepend backup (lists), packager, pkgbase.
Writes .PKGINFO, .BUILDINFO, .MTREE (gzip, makepkg's key set) and the files as root:root,
like makepkg does. Paths in the archive are relative ("usr/...").
"""
import gzip, hashlib, io, json, os, stat, subprocess, sys, tarfile, time

stage, metaf, outdir = sys.argv[1:4]
inst = sys.argv[4] if len(sys.argv) > 4 else None
meta = json.load(open(metaf))
now = int(os.environ.get('SOURCE_DATE_EPOCH', time.time()))

files = []
for root, dirs, fns in os.walk(stage):
    dirs.sort()
    for n in sorted(dirs) + sorted(fns):
        p = os.path.join(root, n)
        files.append(os.path.relpath(p, stage))
files.sort()
# Normalise permissions like a root build with umask 022 (the PC stage may have group-write bits).
for f in files:
    p = os.path.join(stage, f); st = os.lstat(p)
    if stat.S_ISDIR(st.st_mode):
        os.chmod(p, 0o755)
    elif stat.S_ISREG(st.st_mode):
        os.chmod(p, 0o755 if st.st_mode & 0o111 else 0o644)
size = 0
for f in files:
    st = os.lstat(os.path.join(stage, f))
    if stat.S_ISREG(st.st_mode):
        size += st.st_size

def lines(key, vals):
    return ''.join(f'{key} = {v}\n' for v in vals)

pi = f"# Generated by mkpacpkg.py\n"
pi += f"pkgname = {meta['pkgname']}\n"
pi += f"pkgbase = {meta.get('pkgbase', meta['pkgname'])}\n"
pi += f"xdata = pkgtype=pkg\n"
pi += f"pkgver = {meta['pkgver']}\n"
pi += f"pkgdesc = {meta['pkgdesc']}\n"
pi += f"url = {meta.get('url', '')}\n"
pi += f"builddate = {now}\n"
pi += f"packager = {meta.get('packager', 'RX550 G5 port')}\n"
pi += f"size = {size}\n"
pi += f"arch = {meta.get('arch', 'powerpc64')}\n"
pi += lines('license', meta.get('license', []))
pi += lines('replaces', meta.get('replaces', []))
pi += lines('conflict', meta.get('conflicts', []))
pi += lines('provides', meta.get('provides', []))
pi += lines('backup', meta.get('backup', []))
pi += lines('depend', meta.get('depend', []))
pi += lines('optdepend', meta.get('optdepend', []))

bi = (f"format = 2\npkgname = {meta['pkgname']}\npkgbase = {meta.get('pkgbase', meta['pkgname'])}\n"
      f"pkgver = {meta['pkgver']}\npkgarch = {meta.get('arch', 'powerpc64')}\n"
      f"builddate = {now}\npackager = {meta.get('packager', 'RX550 G5 port')}\n"
      f"builddir = /build\nstartdir = /build\nbuildtool = mkpacpkg.py (cross build on x86_64, see README)\n")

special = {'.PKGINFO': pi.encode(), '.BUILDINFO': bi.encode()}
if inst:
    special['.INSTALL'] = open(inst, 'rb').read()

# .MTREE in makepkg's format (bsdtar --format=mtree --options=!all,use-set,type,uid,gid,mode,time,size,sha256,link)
def mt_esc(s):
    out = ''
    for ch in s.encode():
        c = chr(ch)
        if ch <= 32 or ch >= 127 or c in '\\#=':
            out += '\\%03o' % ch
        else:
            out += c
    return out

mt = ['#mtree', '/set type=file uid=0 gid=0 mode=644']
entries = sorted(list(special) + files)
for f in entries:
    if f in special:
        data = special[f]
        mt.append(f"./{mt_esc(f)} time={now}.0 size={len(data)} sha256digest={hashlib.sha256(data).hexdigest()}")
        continue
    p = os.path.join(stage, f); st = os.lstat(p)
    mode = '%o' % stat.S_IMODE(st.st_mode)
    t = f"time={int(st.st_mtime)}.0"
    if stat.S_ISDIR(st.st_mode):
        mt.append(f"./{mt_esc(f)} {t} mode={mode} type=dir")
    elif stat.S_ISLNK(st.st_mode):
        mt.append(f"./{mt_esc(f)} {t} mode=777 type=link link={mt_esc(os.readlink(p))}")
    else:
        h = hashlib.sha256(open(p, 'rb').read()).hexdigest()
        extra = '' if mode == '644' else f" mode={mode}"
        mt.append(f"./{mt_esc(f)} {t}{extra} size={st.st_size} sha256digest={h}")
mtree = gzip.compress(('\n'.join(mt) + '\n').encode(), mtime=now)
special['.MTREE'] = mtree

name = f"{meta['pkgname']}-{meta['pkgver']}-{meta.get('arch', 'powerpc64')}.pkg.tar.zst"
os.makedirs(outdir, exist_ok=True)
out = os.path.join(outdir, name)
buf = io.BytesIO()
with tarfile.open(fileobj=buf, mode='w', format=tarfile.GNU_FORMAT) as tf:
    def add_mem(n, data, mode=0o644):
        ti = tarfile.TarInfo(n); ti.size = len(data); ti.mtime = now; ti.mode = mode
        ti.uid = ti.gid = 0; ti.uname = ti.gname = 'root'
        tf.addfile(ti, io.BytesIO(data))
    for n in ('.BUILDINFO', '.MTREE', '.PKGINFO', '.INSTALL'):
        if n in special:
            add_mem(n, special[n])
    for f in files:
        ti = tf.gettarinfo(os.path.join(stage, f), arcname=f)
        ti.uid = ti.gid = 0; ti.uname = ti.gname = 'root'
        if ti.isreg():
            with open(os.path.join(stage, f), 'rb') as fh:
                tf.addfile(ti, fh)
        else:
            tf.addfile(ti)
subprocess.run(['zstd', '-q', '-19', '-T15', '-f', '-o', out], input=buf.getvalue(), check=True)
print(out)
